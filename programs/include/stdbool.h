/**
 * @file stdbool.h
 * @brief Boolean type and boolean constants.
 *
 * Provides the boolean type and the @c true and @c false constants for
 * representing logical values in C programs.
 */

#ifndef NULLEX_STDBOOL_H
#define NULLEX_STDBOOL_H

/**
 * @brief Boolean type.
 *
 * Maps @c bool to the built-in C @c _Bool type.
 */
#define bool _Bool

/**
 * @brief Boolean value representing true.
 */
#define true 1

/**
 * @brief Boolean value representing false.
 */
#define false 0

#endif